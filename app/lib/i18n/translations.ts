export const TRANSLATIONS: Record<string, Dict> = {
  en, es, fr, de, it, pt, nl, ja, zh, ko, hi, tr, pl, sv, da, no, fi, id, th, vi, he,
};

/** Translate `key` into `lang`, falling back to English. `{var}` interpolation. */
export function t(
  lang: string,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  let value = TRANSLATIONS[lang]?.[key] ?? en[key];
  if (vars) {
    for (const [name, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(v));
    }
  }
  return value;
}
